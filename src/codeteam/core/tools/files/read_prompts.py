"""Тексты инструмента read для агента: описание, параметры, ошибки и вид вывода."""

# Описание инструмента read. line_limit - сколько строк read отдаёт за раз.
READ_DESCRIPTION = """Читает текстовый файл. Первая строка вывода — заголовок [путь],
дальше строки файла в виде "номер:строка". Заголовка и номеров в файле нет.
За раз показывает до {line_limit} строк; большой файл читай частями через offset и limit.
Для папки показывает её содержимое: у текстового файла число строк, у двоичного и большого — размер.
Чтобы найти нужный текст в большом файле, используй grep.
Если не уверен в пути к файлу, найди его через glob по маске.
Закрытые файлы проекта (.env, личные папки других агентов) не читает и в папке не показывает."""

# Описание параметра file_path.
READ_FILE_PATH_DESCRIPTION = "путь файла или папки, абсолютный или относительно папки проекта"

# Описание параметра offset.
READ_OFFSET_DESCRIPTION = "номер строки, с которой читать, от 1"

# Описание параметра limit. line_limit - сколько строк read отдаёт за раз.
READ_LIMIT_DESCRIPTION = "сколько строк прочитать, до {line_limit}"

# Ошибка: offset или limit меньше 1.
READ_OFFSET_LIMIT_ERROR = "Ошибка: offset и limit должны быть не меньше 1"

# Ошибка: offset за концом файла.
READ_OFFSET_ERROR = "Ошибка: offset {offset} больше числа строк в файле ({line_count})"

# Вывод для пустого файла: строка под заголовком файла.
READ_EMPTY_FILE = "(Файл пуст)"

# Итоговая строка, когда показана часть файла. Вид сверяет _PART_SUMMARY_PATTERN в read.py.
READ_PART_SUMMARY = "(Показаны строки {first_number}-{last_number} из {total}. Продолжение: offset = {next_offset})"

# Итоговая строка, когда файл показан до конца. Вид сверяет _END_SUMMARY_PATTERN в read.py.
READ_END_SUMMARY = "(Конец файла, всего строк: {total})"

# Вывод для пустой папки.
READ_EMPTY_DIRECTORY = "Папка {shown_path} пуста"

# Первая строка вывода папки.
READ_DIRECTORY_HEADER = "Папка {shown_path}:"

# Элемент папки: текстовый файл.
READ_TEXT_ENTRY = "{name} (строк: {line_count})"

# Элемент папки: двоичный файл или файл не в UTF-8.
READ_BINARY_ENTRY = "{name} (двоичный или не UTF-8, {size})"

# Элемент папки: большой файл.
READ_LARGE_ENTRY = "{name} (большой, {size})"

# Размер файла в килобайтах.
READ_SIZE_KILOBYTES = "{size} КБ"

# Размер файла в мегабайтах.
READ_SIZE_MEGABYTES = "{size:.1f} МБ"
